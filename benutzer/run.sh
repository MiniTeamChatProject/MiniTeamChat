#!/bin/bash

echo "========================================"
echo "   正在初始化用户微服务环境..."
echo "========================================"

# 1. 检查是否安装了 Go
if ! command -v go &> /dev/null; then
    echo "❌ 错误: 未检测到 Go 环境，请先安装 Go。"
    exit 1
fi

# 2. 整理依赖 (相当于自动下载库)
echo "📦 正在下载依赖库 (go mod tidy)..."
go mod tidy

# 3. 提示数据库配置
echo "----------------------------------------"
echo "⚠️  注意: 请确保本地 PostgreSQL 已启动"
echo "⚠️  数据库名: benutzer_db"
echo "⚠️  配置文件: main.go (如密码不同请自行修改)"
echo "----------------------------------------"

# 4. 启动服务
echo "🚀 正在启动服务..."
go run main.go